"""``roast_target`` - optimised (targeted) transcranial electric stimulation.

Given a lead field generated by ``roast(..., recipe='leadField')`` this finds
the electrode montage that best stimulates one or more brain targets, either
maximising the intensity there or the focality around it.
"""

